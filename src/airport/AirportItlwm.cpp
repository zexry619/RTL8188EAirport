bool AirportItlwm::
setLinkStatus(UInt32 status, const IONetworkMedium * activeMedium, UInt64 speed, OSData * data)
{
    struct ieee80211com *ic = fHalService->get80211Controller();
    struct _ifnet *ifq = &ic->ic_ac.ac_if;
    if (status == currentStatus) {
        return true;
    }
    if ((status & kIONetworkLinkActive) && speed == 0 && ic && ic->ic_bss) {
        struct ieee80211_node *ni = ic->ic_bss;
        if (ni->ni_flags & IEEE80211_NODE_HT) {
            if (ni->ni_chw == IEEE80211_CHAN_WIDTH_40) {
                speed = (ni->ni_flags & IEEE80211_NODE_HT_SGI40) ? 150000000ULL : 135000000ULL;
            } else {
                speed = (ni->ni_flags & IEEE80211_NODE_HT_SGI20) ? 72200000ULL : 65000000ULL;
            }
        } else {
            speed = 54000000ULL;
        }
    }
    bool ret = super::setLinkStatus(status, activeMedium, speed, data);
    currentStatus = status;
    if (fNetIf) {
        if (status & kIONetworkLinkActive) {
#ifdef __PRIVATE_SPI__
            bsdInterface->startOutputThread();
#endif
            auto queue = getWorkQueue();
            if (linkStateThreadCall && (!queue || queue->onThread())) {
                thread_call_enter1(linkStateThreadCall, (thread_call_param_t)(uintptr_t)kIO80211NetworkLinkUp);
            } else {
                getCommandGate()->runAction(setLinkStateGated, (void *)kIO80211NetworkLinkUp, (void *)0);
            }
            /*
             * Kualitas link dilaporkan lewat updateWCLLinkQuality()
             * (WCL), bukan setLinkQualityMetric() — method itu tidak
             * ada di IO80211InfraInterface yang kita pakai.
             */
        } else if (!(status & kIONetworkLinkNoNetworkChange)) {
#ifdef __PRIVATE_SPI__
            bsdInterface->stopOutputThread();
            bsdInterface->flushOutputQueue();
#endif
            ifq_flush(&ifq->if_snd);
            mq_purge(&fHalService->get80211Controller()->ic_mgtq);
            auto queue = getWorkQueue();
            if (linkStateThreadCall && (!queue || queue->onThread())) {
                thread_call_enter1(linkStateThreadCall, (thread_call_param_t)(uintptr_t)kIO80211NetworkLinkDown);
            } else {
                getCommandGate()->runAction(setLinkStateGated, (void *)kIO80211NetworkLinkDown, (void *)(uintptr_t)fHalService->get80211Controller()->ic_deauth_reason);
            }
        }
    }
    return ret;
}

IOReturn AirportItlwm::
setLinkStateGated(OSObject *target, void *arg0, void *arg1, void *arg2, void *arg3)
{
    AirportItlwm *that = OSDynamicCast(AirportItlwm, target);
    if (!that || !that->fNetIf)
        return kIOReturnNotReady;

    auto queue = that->getWorkQueue();
    if (queue && queue->onThread()) {
        /*
         * IO80211Glue::sendIOUCToWcl() explicitly panics ("trying to send on
         * thread panic \n") if called while executing on the WorkQueue thread!
         * If reached here on workloop thread, defer execution to Mach worker
         * thread via thread_call to guarantee queue->onThread() is false.
         */
        XYLog("%s: executing on workloop thread! Deferring to thread_call to prevent panic\n", __FUNCTION__);
        if (that->linkStateThreadCall) {
            thread_call_enter1(that->linkStateThreadCall, (thread_call_param_t)arg0);
            return kIOReturnSuccess;
        }
    }
#ifdef AIRPORT_WCL
    /*
     * bsdInterface->setLinkState() hanya men-set IFF_UP|IFF_RUNNING di
     * ifnet. Yang memberi tahu Skywalk/IO80211 (dan memulai aliran
     * output) adalah fNetIf->setLinkState() versi dua parameter —
     * seperti di cabang non-WCL.
     */
    that->fNetIf->setLinkState((IO80211LinkState)(uint64_t)arg0, 0, false, 0);
    that->bsdInterface->setLinkState((IO80211LinkState)(uint64_t)arg0);
    static_cast<AirportItlwmSkywalkInterface *>(that->fNetIf)->handleWCLLink(
        (IO80211LinkState)(uint64_t)arg0 == kIO80211NetworkLinkUp);
    /*
     * WAJIB juga di jalur WCL.
     *
     * setRunningState() memberi tahu Skywalk bahwa interface siap
     * mengirim/menerima. Tanpa ini Skywalk tidak pernah memanggil
     * outputStart(), sehingga semua paket data tertahan di stack:
     * netstat Opkts=0 dan Oerrs=0 (outputPacket tidak pernah dipanggil),
     * DHCP tidak pernah mengirim discover, dan ping tidak keluar
     * walaupun join + RX sudah berjalan.
     */
    that->fNetIf->setRunningState(
        (IO80211LinkState)(uint64_t)arg0 == kIO80211NetworkLinkUp);
    /*
     * Beri tahu SystemConfiguration bahwa status link berubah.
     *
     * Tanpa ini IPConfiguration tidak pernah melihat link UP dan DHCP
     * tertahan di state INIT selamanya ("DHCP en2: INIT waiting at
     * 34.1 for 8.26"), sehingga tidak ada DHCP discover yang dikirim.
     * Cabang non-WCL di bawah sudah melakukannya; cabang WCL belum.
     */
    that->fNetIf->postMessage(APPLE80211_M_LINK_CHANGED, NULL, 0, false);
    if ((IO80211LinkState)(uint64_t)arg0 == kIO80211NetworkLinkUp) {
        that->fNetIf->postMessage(APPLE80211_M_BSSID_CHANGED, NULL, 0, false);
        that->fNetIf->postMessage(APPLE80211_M_SSID_CHANGED, NULL, 0, false);
    }
    return kIOReturnSuccess;
#else
    IOReturn ret = that->fNetIf->setLinkState((IO80211LinkState)(uint64_t)arg0, (unsigned int)(uint64_t)arg1);
    that->fNetIf->setRunningState((IO80211LinkState)(uint64_t)arg0 == kIO80211NetworkLinkUp);
    that->fNetIf->postMessage(APPLE80211_M_LINK_CHANGED, NULL, 0, false);
    that->fNetIf->postMessage(APPLE80211_M_BSSID_CHANGED, NULL, 0, false);
    that->fNetIf->postMessage(APPLE80211_M_SSID_CHANGED, NULL, 0, false);
    if ((IO80211LinkState)(uint64_t)arg0 == kIO80211NetworkLinkUp) {
        that->fNetIf->reportLinkStatus(3, 0x80);
    } else {
        that->fNetIf->reportLinkStatus(1, 0);
    }
    that->bsdInterface->setLinkState((IO80211LinkState)(uint64_t)arg0);
    return ret;
#endif
}

