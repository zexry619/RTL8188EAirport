static void handleLinkStateThread(thread_call_param_t param0, thread_call_param_t param1)
{
    AirportItlwm *self = (AirportItlwm *)param0;
    if (!self || !self->fNetIf)
        return;

    IO80211LinkState state = (IO80211LinkState)(uintptr_t)param1;
    uint32_t reason = 0;
    if (state == kIO80211NetworkLinkDown && self->fHalService) {
        auto ic = self->fHalService->get80211Controller();
        if (ic)
            reason = (uint32_t)ic->ic_deauth_reason;
    }

    self->getCommandGate()->runAction(
        AirportItlwm::setLinkStateGated,
        (void *)(uintptr_t)state,
        (void *)(uintptr_t)reason);
}

void AirportItlwm::releaseAll()
{
#ifdef AIRPORT_WCL
    if (fNetIf)
        static_cast<AirportItlwmSkywalkInterface *>(fNetIf)->stopWCL();
    OSSafeReleaseNULL(driverFaultReporter);
    OSSafeReleaseNULL(driverCoreFaultReporter);
    OSSafeReleaseNULL(driverFaultStream);
    OSSafeReleaseNULL(driverLogger);
    // Stop only successfully started pipes, while their owner workloop exists.
    if (driverSnapshotsPipeStarted) {
        driverSnapshotsPipe->CCPipe::stopPipe();
        driverSnapshotsPipeStarted = false;
    }
    if (driverDataPathPipeStarted) {
        driverDataPathPipe->CCPipe::stopPipe();
        driverDataPathPipeStarted = false;
    }
    if (driverLogPipeStarted) {
        driverLogPipe->CCPipe::stopPipe();
        driverLogPipeStarted = false;
    }
#endif
    OSSafeReleaseNULL(driverLogPipe);
    OSSafeReleaseNULL(driverDataPathPipe);
    OSSafeReleaseNULL(driverSnapshotsPipe);
#ifndef AIRPORT_WCL
    OSSafeReleaseNULL(driverFaultReporter);
#endif
    /*
     * Timer harus mati SEBELUM fHalService dilepas: aksi timer
     * (watchdogAction/fakeScanDone) memakai fHalService. Kalau timer
     * menembak di jendela antara release HAL dan cancel → NULL deref.
     */
    if (watchdogTimer) {
        watchdogTimer->cancelTimeout();
        watchdogTimer->disable();
        if (_fWorkloop)
            _fWorkloop->removeEventSource(watchdogTimer);
        watchdogTimer->release();
        watchdogTimer = NULL;
    }
    if (scanSource) {
        scanSource->cancelTimeout();
        scanSource->disable();
        if (_fWorkloop)
            _fWorkloop->removeEventSource(scanSource);
        scanSource->release();
        scanSource = NULL;
    }
    if (fHalService) {
        fHalService->release();
        fHalService = NULL;
    }
    if (_fWorkloop) {
        if (_fCommandGate) {
//            _fCommandGate->disable();
            _fWorkloop->removeEventSource(_fCommandGate);
            _fCommandGate->release();
            _fCommandGate = NULL;
        }
        _fWorkloop->release();
        _fWorkloop = NULL;
    }
    if (linkStateThreadCall) {
        thread_call_cancel(linkStateThreadCall);
        thread_call_free(linkStateThreadCall);
        linkStateThreadCall = NULL;
    }
    unregistPM();
}

void AirportItlwm::
eventHandler(struct ieee80211com *ic, int msgCode, void *data)
{
    AirportItlwm *that = OSDynamicCast(AirportItlwm, ic->ic_ac.ac_if.controller);
#ifdef AIRPORT_WCL
    if (!that)
        return;
#endif
    IO80211SkywalkInterface *interface = that->fNetIf;
    if (!interface)
        return;
#ifdef AIRPORT_WCL
    static_cast<AirportItlwmSkywalkInterface *>(interface)->handleWCLEvent(msgCode, data);
#else
    switch (msgCode) {
        case IEEE80211_EVT_COUNTRY_CODE_UPDATE:
            interface->postMessage(APPLE80211_M_COUNTRY_CODE_CHANGED, NULL, 0, 0);
            break;
        case IEEE80211_EVT_STA_ASSOC_DONE:
            interface->postMessage(APPLE80211_M_ASSOC_DONE, NULL, 0, 0);
            break;
        case IEEE80211_EVT_STA_DEAUTH:
            interface->postMessage(APPLE80211_M_DEAUTH_RECEIVED, NULL, 0, 0);
            break;
        default:
            break;
    }
#endif
}

void AirportItlwm::watchdogAction(IOTimerEventSource *timer)
{
    if (!fHalService)
        return;
    struct _ifnet *ifp = &fHalService->get80211Controller()->ic_ac.ac_if;
    if (!ifp->if_watchdog)
        return;
    (*ifp->if_watchdog)(ifp);

    watchdogTimer->setTimeoutMS(kWatchDogTimerPeriod);
}

void AirportItlwm::fakeScanDone(OSObject *owner, IOTimerEventSource *sender)
{
#ifndef AIRPORT_WCL
    UInt32 msg = 0;
#endif
    AirportItlwm *that = (AirportItlwm *)owner;
#ifdef AIRPORT_WCL
    if (that->fNetIf)
        static_cast<AirportItlwmSkywalkInterface *>(that->fNetIf)->completeWCLScan();
#else
    that->fNetIf->postMessage(APPLE80211_M_SCAN_DONE, &msg, 4, 0);
#endif
}

bool AirportItlwm::init(OSDictionary *properties)
{
    XYLog("%s\n", __PRETTY_FUNCTION__);
    bool ret = super::init(properties);
    awdlSyncEnable = true;
    power_state = 0;
    /*
     * Harus 0: setLinkStatus() early-return kalau status == currentStatus.
     * Tanpa inisialisasi, nilai awal tak tentu — kalau kebetulan sama
     * dengan kIONetworkLinkValid|kIONetworkLinkActive, pemberitahuan
     * link UP pertama tidak pernah diteruskan ke IO80211 dan interface
     * tetap "inactive" (DHCP tidak jalan).
     */
    currentStatus = 0;
    linkStateThreadCall = NULL;
    memset(geo_location_cc, 0, sizeof(geo_location_cc));
    return ret;
}

IOService* AirportItlwm::probe(IOService *provider, SInt32 *score)
{
    IOLog("rtl8188e: AirportItlwm::probe called!\n");
    XYLog("%s\n", __PRETTY_FUNCTION__);
    IOPCIEDeviceWrapper *wrapper = OSDynamicCast(IOPCIEDeviceWrapper, provider);
    if (!wrapper) {
        IOLog("rtl8188e: AirportItlwm provider bukan IOPCIEDeviceWrapper\n");
        XYLog("%s Not a IOPCIEDeviceWrapper instance\n", __FUNCTION__);
        return NULL;
    }
    pciNub = wrapper->pciNub;
    fHalService = wrapper->fHalService;
    /* M4: wrapper USB tidak punya pciNub; HAL memegang IOUSBHostInterface. */
    if (!fHalService) {
        IOLog("rtl8188e: AirportItlwm wrapper tanpa HAL service\n");
        XYLog("%s wrapper tanpa HAL service\n", __FUNCTION__);
        return NULL;
    }
    IOLog("rtl8188e: AirportItlwm::probe BERHASIL\n");
    return super::probe(provider, score);
}

